"""Emit fp32_tiles.h: AVX-512 NT (dot-product) FP32 tiles for fp32_gemm.c, one function per (R, C).

tile_R_C(x, ldx, xs, w, ldw, K, y, ldy, pf, npf): y[r][c] = sum_k x[r][k] * w[c][k] for R activation rows and C
weight rows, both K-contiguous (the original [N, K] weight layout). Named accumulators (an __m512 array makes
GCC copy the tile through the stack). The smaller of R and C is held in registers each k step and the other
streamed. K % 16 == 0. Activation r's k is at x[r * ldx + k * xs] (xs = 1 row-major, R for
tiles packed [K/16][R][16]). Reduction: the flattened accumulators (r-major) in groups of 16 / 8 / 4 / 1.
pf/npf: rows of the next weight block to prefetch, one line per row per k step.

python gen_fp32_tiles.py > fp32_tiles.h
"""
RMAX, CMAX, AMAX = 8, 12, 28

print("// Generated by gen_fp32_tiles.py; do not edit.")
print(r"""#include <immintrin.h>
#include <stddef.h>

#ifndef PF_HINT
#define PF_HINT _MM_HINT_T0
#endif

static inline __attribute__((always_inline)) __m512 pair(__m512 a, __m512 b) {
    return _mm512_add_ps(_mm512_unpacklo_ps(a, b), _mm512_unpackhi_ps(a, b));
}
static inline __attribute__((always_inline)) __m512 quad(__m512 ab, __m512 cd) {
    __m512d x = _mm512_castps_pd(ab), y = _mm512_castps_pd(cd);
    return _mm512_add_ps(_mm512_castpd_ps(_mm512_unpacklo_pd(x, y)), _mm512_castpd_ps(_mm512_unpackhi_pd(x, y)));
}
// 4 accumulators -> each 128-bit group holds the 4 partial sums
static inline __attribute__((always_inline)) __m512 four(__m512 a, __m512 b, __m512 c, __m512 d) {
    return quad(pair(a, b), pair(c, d));
}
static inline __attribute__((always_inline)) __m128 reduce4(__m512 a, __m512 b, __m512 c, __m512 d) {
    __m512 v = four(a, b, c, d);
    __m256 h = _mm256_add_ps(_mm512_castps512_ps256(v), _mm512_extractf32x8_ps(v, 1));
    return _mm_add_ps(_mm256_castps256_ps128(h), _mm256_extractf128_ps(h, 1));
}
static inline __attribute__((always_inline)) __m256 reduce8(__m512 a, __m512 b, __m512 c, __m512 d, __m512 e,
                                                            __m512 f, __m512 g, __m512 h) {
    __m512 p = four(a, b, c, d), q = four(e, f, g, h);
    __m512 s = _mm512_add_ps(_mm512_shuffle_f32x4(p, q, _MM_SHUFFLE(2, 0, 2, 0)),
                             _mm512_shuffle_f32x4(p, q, _MM_SHUFFLE(3, 1, 3, 1)));  // [p01 p23 q01 q23]
    s = _mm512_shuffle_f32x4(s, s, _MM_SHUFFLE(3, 1, 2, 0));                         // [p01 q01 p23 q23]
    return _mm256_add_ps(_mm512_castps512_ps256(s), _mm512_extractf32x8_ps(s, 1));
}
static inline __attribute__((always_inline)) __m512 reduce16(__m512 a, __m512 b, __m512 c, __m512 d, __m512 e,
                                                             __m512 f, __m512 g, __m512 h, __m512 i, __m512 j,
                                                             __m512 k, __m512 l, __m512 m, __m512 n, __m512 o,
                                                             __m512 p) {
    __m512 v0 = four(a, b, c, d), v1 = four(e, f, g, h), v2 = four(i, j, k, l), v3 = four(m, n, o, p);
    __m512 w0 = _mm512_add_ps(_mm512_shuffle_f32x4(v0, v1, _MM_SHUFFLE(2, 0, 2, 0)),
                              _mm512_shuffle_f32x4(v0, v1, _MM_SHUFFLE(3, 1, 3, 1)));
    __m512 w1 = _mm512_add_ps(_mm512_shuffle_f32x4(v2, v3, _MM_SHUFFLE(2, 0, 2, 0)),
                              _mm512_shuffle_f32x4(v2, v3, _MM_SHUFFLE(3, 1, 3, 1)));
    return _mm512_add_ps(_mm512_shuffle_f32x4(w0, w1, _MM_SHUFFLE(2, 0, 2, 0)),
                         _mm512_shuffle_f32x4(w0, w1, _MM_SHUFFLE(3, 1, 3, 1)));
}
typedef void (*Tile)(const float *, int, int, const float *, int, int, float *, int, const float *const *, int);
""")


def tile(R, C):
    acc = [f"a{r}_{c}" for r in range(R) for c in range(C)]
    out = [f"static __attribute__((noinline)) void tile_{R}_{C}(const float *restrict x, int ldx, int xs, const float *restrict w, "
           f"int ldw, int K, float *restrict y, int ldy, const float *const *pf, int npf) {{"]
    out.append("    " + " ".join(f"__m512 {a} = _mm512_setzero_ps();" for a in acc))
    out.append("    for (int k = 0; k < K; k += 16) {")
    out.append("        for (int p = 0; p < npf; ++p) _mm_prefetch((const char *)(pf[p] + k), PF_HINT);")
    if C <= R:  # hold weights, stream activations
        for c in range(C):
            out.append(f"        const __m512 w{c} = _mm512_loadu_ps(w + {c} * (size_t)ldw + k);")
        for r in range(R):
            body = " ".join(f"a{r}_{c} = _mm512_fmadd_ps(v, w{c}, a{r}_{c});" for c in range(C))
            out.append(f"        {{ const __m512 v = _mm512_loadu_ps(x + {r} * (size_t)ldx + (size_t)k * xs); {body} }}")
    else:  # hold activations, stream weights
        for r in range(R):
            out.append(f"        const __m512 x{r} = _mm512_loadu_ps(x + {r} * (size_t)ldx + (size_t)k * xs);")
        for c in range(C):
            body = " ".join(f"a{r}_{c} = _mm512_fmadd_ps(x{r}, v, a{r}_{c});" for r in range(R))
            out.append(f"        {{ const __m512 v = _mm512_loadu_ps(w + {c} * (size_t)ldw + k); {body} }}")
    out.append("    }")
    out.append(f"    float t[{(len(acc) + 15) // 16 * 16}] __attribute__((aligned(64)));")
    i = 0
    while i < len(acc):
        left = len(acc) - i
        if left >= 16:
            out.append(f"    _mm512_store_ps(t + {i}, reduce16({', '.join(acc[i:i + 16])}));"); i += 16
        elif left >= 8:
            out.append(f"    _mm256_store_ps(t + {i}, reduce8({', '.join(acc[i:i + 8])}));"); i += 8
        elif left >= 4:
            out.append(f"    _mm_store_ps(t + {i}, reduce4({', '.join(acc[i:i + 4])}));"); i += 4
        else:
            out.append(f"    t[{i}] = _mm512_reduce_add_ps({acc[i]});"); i += 1
    for r in range(R):
        out.append("    " + " ".join(f"y[{r} * (size_t)ldy + {c}] = t[{r * C + c}];" for c in range(C)))
    out.append("}")
    return "\n".join(out)


shapes = [(r, c) for r in range(1, RMAX + 1) for c in range(1, CMAX + 1) if r * c <= AMAX]
for r, c in shapes:
    print(tile(r, c))
print(f"static const Tile TILES[{RMAX + 1}][{CMAX + 1}] = {{")
for r in range(RMAX + 1):
    print("    {" + ", ".join(f"tile_{r}_{c}" if (r, c) in shapes else "0" for c in range(CMAX + 1)) + "},")
print("};")
