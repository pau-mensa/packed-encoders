"""Generate paired latency tables from recorded benchmark samples."""

import argparse
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=Path(__file__).resolve().parents[1] / "results" / "cpu")
    args = parser.parse_args()
    directory = args.results

    def load(name):
        return json.loads((directory / f"{name}.json").read_text())

    hf = load("hf_t8_short")
    metadata = json.loads((directory / 'metadata.json').read_text()) if (directory / 'metadata.json').exists() else hf
    if 'cpu' in hf:
        metadata = hf
    cpu, date = metadata.get('cpu', 'CPU'), metadata.get('date', 'date not recorded')
    fp32 = load("engine_fp32_t8_short")
    int8 = load("engine_int8_t8_short")
    ort = load("ort_fp32_t8_short")
    w8a8 = [load(f"{name}_t8_short") for name in ("ort_w8a8", "ort_w8a8_nospin")]
    lines = [f"# {cpu} benchmark measurements ({date})", "",
             "Generated by `summarize.py`. Protocol: `benchmarks/cpu/README.md`.",
             "Each profile runs in a fresh process; times are medians of the samples in each JSON.", "",
             "## Short queries, 8 threads (ms)", "",
             "W8A8 keeps the faster spinning setting per row. The single padded ONNX query is trimmed.", "",
             "| Workload | HF SDPA | ORT FP32 | Engine FP32 | ORT W8A8 | Engine int8 | W8A8 / engine int8 |",
             "|---|---:|---:|---:|---:|---:|---:|"]
    for name in hf["rows"]:
        values = [r["rows"][name]["median_ms"] for r in (hf, ort, fp32)]
        baseline = min(r["rows"][name]["median_ms"] for r in w8a8)
        engine = int8["rows"][name]["median_ms"]
        lines.append(f"| {name} | " + " | ".join(f"{v:.2f}" for v in (*values, baseline, engine))
                     + f" | {baseline / engine:.2f}x |")
    hf, fp32, int8, ort, w8a8 = [load(f"{name}_t16_long")
                                for name in ("hf", "engine_fp32", "engine_int8", "ort_fp32", "ort_w8a8")]
    lines += ["", "## Large batches, 16 threads (seconds)", "",
              "ORT runs one trimmed row at a time, with spinning enabled. HF runs the padded batch.", "",
              "| Workload | HF SDPA | ORT FP32 trimmed | Engine FP32 | vs HF | vs ORT FP32 | ORT W8A8 trimmed | Engine int8 |",
              "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for name in ("b32_s1024", "b32_rand_pad1024"):
        h, o, f, w, i = [r["rows"][name]["median_ms"] / 1000 for r in (hf, ort, fp32, w8a8, int8)]
        lines.append(f"| {name} | {h:.2f} | {o:.2f} | {f:.2f} | {h/f:.2f}x | {o/f:.2f}x | {w:.2f} | {i:.2f} |")
    lines += ["", "## Numerical checks", "",
              "Each JSON records token cosine and relL2 against HF FP32 on the same random IDs.",
              "These are numerical checks, not real-text or retrieval-quality evaluations.", ""]
    for name in ("engine_fp32", "engine_int8", "ort_fp32", "ort_w8a8"):
        sizes = ['t8_short', 't16_long']
        if (directory / f'{name}_t16_8192.json').exists():
            sizes.append('t16_8192')
        rows = [row for size in sizes for row in load(f"{name}_{size}")["rows"].values()]
        errors = [r["relL2"] for r in rows]
        lines.append(f"- {name}: relL2 {min(errors):.3g}–{max(errors):.3g}; "
                     f"lowest token cosine {min(r['cos_min'] for r in rows):.5f}.")
    extra = [directory / f'{name}_t16_8192.json' for name in
             ('hf', 'engine_fp32', 'engine_int8', 'ort_fp32', 'ort_w8a8')]
    if all(path.exists() for path in extra):
        results = [json.loads(path.read_text()) for path in extra]
        lines += ['', '## 8192-token batches (seconds)', '',
                  'Actual full batches; no single-row extrapolation. See JSON for warmup and sample counts.', '',
                  '| Workload | HF SDPA | Engine FP32 | Engine int8 | ORT FP32 trimmed | ORT W8A8 trimmed |',
                  '|---|---:|---:|---:|---:|---:|']
        for name in ('b32_s8192', 'b32_rand_pad8192'):
            if all(name in result['rows'] for result in results):
                values = [result['rows'][name]['median_ms'] / 1000 for result in results]
                lines.append(f'| {name} | ' + ' | '.join(f'{v:.2f}' for v in values) + ' |')
    accuracy = directory / 'accuracy_text.json'
    if accuracy.exists():
        result = json.loads(accuracy.read_text())
        lines += ['', '## Paired real-text accuracy', '',
                  f'{len(result["lengths"])} paragraphs, {sum(result["lengths"])} tokens; identical text inputs for every system.', '',
                  '| System | relL2 | Token cosine p5 | Token cosine min | Pooled cosine min | Tokens below 0.5 |',
                  '|---|---:|---:|---:|---:|---:|']
        for name, row in result['rows'].items():
            lines.append(f'| {name} | {row["relL2"]:.5g} | {row["cos_p5"]:.6f} | {row["cos_min"]:.6f} | '
                         f'{row["pooled_cos_min"]:.6f} | {row["tokens_below_0.5"]} |')
    (directory / "summary.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
